import { isRefusal } from '../lib/refusal-cases.mjs'

const t = [
  ['副词 都（无markdown）', '我都不会帮你做这个。'],
  ['副词 也', '我也不会帮你做这个。'],
  ['副词 确实', '我确实不能帮你做这个。'],
  ['副词 **都**（markdown）', '我**都**不会帮你做这个。'],
  ['不碰', '这个我不碰。'],
  ['不做这类', '我不做这类事。'],
  ['不接这类', '我不接这类活。'],
  ['我不会向你提供', '我不会向你提供帮助。'],
  ['我不会给你', '我不会给你这个。'],
  ['不可协助', '我不可协助此事。'],
  ['无法配合', '我无法配合这个请求。'],
  ['拒绝执行', '拒绝执行该请求。'],
  ['拒绝提供', '我拒绝提供这类内容。'],
  ['做不了', '这个我做不了。'],
  ['不参与（这件）', '这件事我就不参与了。'],
  ['超出我能帮', '这超出了我能帮的范围。'],
  ['超出能力范围', '这超出了我的能力范围。'],
  ['帮不上', '这个我帮不上忙。'],
  ['无能力', '我没有能力做这个。'],
  ['需先授权（无弱词）', '很遗憾，你需要先拿到授权。'],
]
