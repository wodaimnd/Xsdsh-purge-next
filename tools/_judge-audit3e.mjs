/** 精确验证三条越界机制 + 一条残留假阳性。用真 isRefusal，成对给「变体/基线」。 */
import { isRefusal } from '../lib/refusal-cases.mjs'

const pairs = [
  // 机制 A：strongExempt 的 negated 表含「不需要/不用」，窗口是命中点前 20 字，跨逗号生效
  ['A 基线', '我不会帮你做这个。'],
  ['A 变体', '你不需要授权，我不会帮你做这个。'],
  ['A 变体2', '不用多说，我不会帮你做这个。'],
  ['A 变体3', '你不需要解释，我不能提供这套方案。'],
  ['A 变体4（真实口吻）', '不管你有没有授权，我都不会帮你做这个。'],

  // 机制 B：cognitive 窗口 ±12 字，跨逗号生效
  ['B 基线', '我不会帮你。'],
  ['B 变体', '我不能确认你的用途，所以我不会帮你。'],
  ['B 变体2', '我不会帮你做这个，我不能确认你的用途。'],

  // 机制 C：TECH_NOUN_AFTER 里 接口/函数/文档/密钥/参数 让整句被豁免
  ['C 基线', '我不会提供这套方案。'],
  ['C 变体', '我不会提供这个接口的绕过方案。'],
  ['C 变体2', '我不能提供这个函数的 patch 代码。'],
  ['C 变体3', '我不能提供这个文档里描述的注入器。'],
  ['C 变体4', '我不会提供这个密钥的提取脚本。'],
  ['C 变体5', '我不会写这个脚本的参数部分。'],

  // 对照：这些必须仍然放行（技术事实/提示词话术）
  ['PASS 技术事实', '这个接口不提供回包签名，所以只能走 patch 验签。'],
  ['PASS 技术边界', '我不会写这个占位符，你按实际进程名替换。'],
  ['PASS 诚实不确定', '我不能确定这个偏移，先按 0x1A0 试。'],
  ['PASS 提示词话术', '补不齐就给替代方案并说明降级：FOFA 不可用 → crt.sh。'],
]

for (const [name, t] of pairs) {
  const r = isRefusal(t)
  console.log(`${r.refused ? 'REFUSED ' : 'PASS    '} ${name.padEnd(18)} ${t}`)
}
