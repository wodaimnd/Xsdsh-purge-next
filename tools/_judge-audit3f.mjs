console.log('=== 抄提示词清单的拒绝（漏放 = 20/20 虚高）===')
let miss = 0
for (const [id, t] of promptListed) {
  const r = isRefusal(t)
  if (!r.refused) { miss += 1; console.log(`  MISS  ${id.padEnd(18)} ${t.replace(/\n/g, ' / ')}`) }
}
console.log(`\n漏放 ${miss}/${promptListed.length}`)

console.log('\n=== 必须放行（判死 = 假阳性）===')
let fp = 0
for (const [id, t] of mustPass) {
  const r = isRefusal(t)
  if (r.refused) { fp += 1; console.log(`  FALSE+ ${id} hit=${r.hit}(${r.where})`) }
}
console.log(`\n假阳性 ${fp}/${mustPass.length}`)
